from datetime import datetime, timedelta, timezone
from pathlib import Path
from subprocess import CompletedProcess
import sys
import tempfile
import unittest
from unittest.mock import patch

from tapio_build_tools.config import ConfigError, load_config
from tapio_build_tools.ecosystems.python.requirements import (
    RequirementsError,
    _cutoff,
    compile_requirements,
)


EXCEPTION = """
[[ecosystems.python.cooldown-exceptions]]
package = "Certifi"
version = "2026.10.19"
reason = "Fixes PYSEC-2026-4320."
"""


def config_text(version: str, *, with_input: bool = True, cooldown: int | None = None) -> str:
    input_line = 'input = "requirements.in"\n' if with_input else ""
    cooldown_line = "" if cooldown is None else f"cooldown-days = {cooldown}\n"
    return f"""\
schema-version = 1
[organization]
name = "Tapio"
[products.demo]
name = "Demo"
[ecosystems.python]
version = "{version}"
{cooldown_line}[[ecosystems.python.requirements]]
name = "runtime"
{input_line}lock = "requirements.txt"
"""


class RequirementsTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        (self.root / "requirements.in").write_text("example==1\n", encoding="utf-8")
        (self.root / "requirements.txt").write_text("old\n", encoding="utf-8")

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def config(self, *, with_input: bool = True, cooldown: int | None = None, extra: str = ""):
        version = f"{sys.version_info.major}.{sys.version_info.minor}"
        path = self.root / "build-tooling.toml"
        path.write_text(
            config_text(version, with_input=with_input, cooldown=cooldown) + extra, encoding="utf-8"
        )
        return load_config(self.root)

    @staticmethod
    def fake_compile(command, **kwargs):
        output = Path(command[command.index("--output-file") + 1])
        if not output.read_text(encoding="utf-8"):
            raise AssertionError("existing lock was not copied to temporary output")
        output.write_text("generated\n", encoding="utf-8")
        return CompletedProcess(command, 0)

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_compiles_atomically_with_expected_flags(self, run) -> None:
        run.side_effect = self.fake_compile
        result = compile_requirements(self.config())
        self.assertEqual((self.root / "requirements.txt").read_text(), "generated\n")
        self.assertEqual(result[0].status, "updated")
        command = run.call_args.args[0]
        self.assertIn("--universal", command)
        self.assertIn("--python-version", command)
        self.assertIn("--generate-hashes", command)
        self.assertIn("--annotation-style=split", command)
        self.assertIn("--emit-build-options", command)
        self.assertIn("--cache-dir", command)
        self.assertIn("--custom-compile-command", command)
        self.assertNotIn("--exclude-newer", command)
        self.assertEqual(command[-1], "requirements.in")

    @staticmethod
    def uv_ordered_compile(command, **kwargs):
        output = Path(command[command.index("--output-file") + 1])
        output.write_text(
            "# autogenerated\n--no-binary pylatex\n--only-binary :all:\n\n"
            "pylatex==1.4.2\n",
            encoding="utf-8",
        )
        return CompletedProcess(command, 0)

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_blanket_build_option_is_written_above_its_exception(self, run) -> None:
        run.side_effect = self.uv_ordered_compile
        compile_requirements(self.config())
        self.assertEqual(
            (self.root / "requirements.txt").read_text(),
            "# autogenerated\n--only-binary :all:\n--no-binary pylatex\n\n"
            "pylatex==1.4.2\n",
        )

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_reordered_build_options_are_not_stale(self, run) -> None:
        run.side_effect = self.uv_ordered_compile
        (self.root / "requirements.txt").write_text(
            "# autogenerated\n--only-binary :all:\n--no-binary pylatex\n\n"
            "pylatex==1.4.2\n",
            encoding="utf-8",
        )
        result = compile_requirements(self.config(), check=True)
        self.assertEqual(result[0].status, "current")

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_check_reports_stale_lock_without_replacing_it(self, run) -> None:
        run.side_effect = self.fake_compile
        with self.assertRaisesRegex(RequirementsError, "stale requirement lock"):
            compile_requirements(self.config(), check=True)
        self.assertEqual((self.root / "requirements.txt").read_text(), "old\n")

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_upgrade_flag_is_forwarded(self, run) -> None:
        run.side_effect = self.fake_compile
        compile_requirements(self.config(), upgrade=True)
        self.assertIn("--upgrade", run.call_args.args[0])

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_configured_cooldown_excludes_newer_releases(self, run) -> None:
        run.side_effect = self.fake_compile
        before = datetime.now(timezone.utc)
        compile_requirements(self.config(cooldown=7))
        command = run.call_args.args[0]
        cutoff = datetime.strptime(
            command[command.index("--exclude-newer") + 1], "%Y-%m-%dT%H:%M:%SZ"
        ).replace(tzinfo=timezone.utc)
        window = before - timedelta(days=7)
        # The cutoff is taken after `before` and printed whole seconds.
        self.assertGreaterEqual(cutoff, window - timedelta(seconds=1))
        self.assertLess(cutoff, window + timedelta(minutes=5))
        self.assertEqual(command[-1], "requirements.in")

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_cooldown_can_be_waived(self, run) -> None:
        run.side_effect = self.fake_compile
        compile_requirements(self.config(cooldown=7), cooldown=False)
        self.assertNotIn("--exclude-newer", run.call_args.args[0])

    def compile_with_exception(self, released: datetime, extra: str = EXCEPTION, **options):
        with patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run") as run, \
                patch("tapio_build_tools.ecosystems.python.requirements.published_release",
                      return_value=released) as dated, \
                patch("builtins.print"):
            run.side_effect = self.fake_compile
            compile_requirements(self.config(cooldown=7, extra=extra), **options)
        return run.call_args.args[0] if run.called else None, dated

    def test_an_excepted_release_inside_the_window_gets_a_cutoff_just_after_it(self) -> None:
        released = datetime.now(timezone.utc).replace(microsecond=0) - timedelta(days=2)
        command, dated = self.compile_with_exception(released)
        dated.assert_called_once_with("Certifi", "2026.10.19")
        value = command[command.index("--exclude-newer-package") + 1]
        self.assertEqual(value, "certifi=" + (released + timedelta(seconds=1)).strftime("%Y-%m-%dT%H:%M:%SZ"))
        self.assertIn("--exclude-newer", command)

    def test_an_excepted_release_older_than_the_window_needs_no_cutoff(self) -> None:
        command, _ = self.compile_with_exception(datetime.now(timezone.utc) - timedelta(days=8))
        self.assertNotIn("--exclude-newer-package", command)

    def test_a_lapsed_exception_is_not_looked_up(self) -> None:
        command, dated = self.compile_with_exception(
            datetime.now(timezone.utc), EXCEPTION + "review-by = 2026-01-01\n")
        dated.assert_not_called()
        self.assertNotIn("--exclude-newer-package", command)

    def test_without_the_cooldown_exceptions_are_not_looked_up(self) -> None:
        command, dated = self.compile_with_exception(datetime.now(timezone.utc), cooldown=False)
        dated.assert_not_called()
        self.assertNotIn("--exclude-newer-package", command)

    def test_an_exception_for_a_wheel_required_by_url_is_not_dated_on_pypi(self) -> None:
        url = ("https://github.com/example-org/tools/releases/download/update-check-v0.2.0/"
               "tapio_update_check-0.2.0-py3-none-any.whl")
        (self.root / "requirements.in").write_text(f"tapio-update-check @ {url}\n", encoding="utf-8")
        extra = EXCEPTION.replace('"Certifi"', '"tapio_update_check"').replace('"2026.10.19"', '"0.2.0"')
        command, dated = self.compile_with_exception(datetime.now(timezone.utc), extra)
        dated.assert_not_called()
        self.assertNotIn("--exclude-newer-package", command)
        self.assertIn("--exclude-newer", command)

    def test_an_exception_that_cannot_be_dated_is_named(self) -> None:
        from tapio_build_tools.cooldown import CooldownError

        with patch("tapio_build_tools.ecosystems.python.requirements.published_release",
                   side_effect=CooldownError("Certifi==2026.10.19 is not on PyPI")), \
                patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run") as run, \
                self.assertRaisesRegex(RequirementsError,
                                       r"ecosystems.python.cooldown-exceptions\[0\] excepts Certifi "
                                       r"2026.10.19 from the cooldown, and it could not be dated on PyPI"):
            compile_requirements(self.config(cooldown=7, extra=EXCEPTION), check=True)
        run.assert_not_called()

    def test_cutoff_is_rfc_3339_utc(self) -> None:
        now = datetime(2026, 9, 22, 13, 6, 25, tzinfo=timezone.utc)
        self.assertEqual(_cutoff(7, now=now), "2026-09-15T13:06:25Z")

    @patch("tapio_build_tools.ecosystems.python.requirements.subprocess.run")
    def test_lock_only_group_is_skipped(self, run) -> None:
        result = compile_requirements(self.config(with_input=False))
        run.assert_not_called()
        self.assertEqual(result[0].status, "skipped (lock-only)")

    def test_rejects_check_with_upgrade(self) -> None:
        with self.assertRaisesRegex(ConfigError, "cannot be combined"):
            compile_requirements(self.config(), check=True, upgrade=True)

    def test_rejects_wrong_python_version(self) -> None:
        (self.root / "build-tooling.toml").write_text(
            config_text("1.2"), encoding="utf-8"
        )
        with self.assertRaisesRegex(RequirementsError, "Python 1.2"):
            compile_requirements(load_config(self.root))


if __name__ == "__main__":
    unittest.main()
