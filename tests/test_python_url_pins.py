WHEEL = "gadget_lib-0.1.0-py3-none-any.whl"
URL = f"https://github.com/example-org/gadget-tools/releases/download/gadget-lib-v0.1.0/{WHEEL}"
DIGEST = "d" * 64

LOCK = f"""\
# This file was autogenerated by uv via the following command:
#    tapio-build --project . python requirements compile
--only-binary :all:

cryptography==50.0.1 \\
    --hash=sha256:{"a" * 64}
    # via gadget-lib
gadget-lib @ {URL} \\
    --hash=sha256:{DIGEST}
    # via -r requirements.in
packaging==26.2 \\
    --hash=sha256:{"b" * 64}
"""


class LockFixture(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.lock = self.root / "requirements.txt"

    def pins(self, text: str = LOCK) -> dict[str, Pin]:
        self.lock.write_text(text, encoding="utf-8")
        return {pin.name: pin for pin in read_pins(self.lock)}


class ReadingAUrlPinTest(LockFixture):
    def test_it_is_read_with_its_wheels_version_and_its_one_hash(self) -> None:
        pins = self.pins()

        self.assertEqual(set(pins), {"cryptography", "gadget-lib", "packaging"})
        pin = pins["gadget-lib"]
        self.assertEqual((pin.version, pin.url, pin.hashes), ("0.1.0", URL, frozenset({DIGEST})))
        self.assertEqual(pin.label, f"gadget-lib 0.1.0 ({URL})")
        self.assertEqual(pin.asset.api_url,
                         "https://api.github.com/repos/example-org/gadget-tools"
                         "/releases/tags/gadget-lib-v0.1.0")
        self.assertEqual(pins["packaging"].url, "")

    def test_a_marker_after_the_url_is_not_part_of_it(self) -> None:
        pins = self.pins(f"gadget-lib @ {URL} ; sys_platform == 'win32' \\\n"
                         f"    --hash=sha256:{DIGEST}\n")
        self.assertEqual(pins["gadget-lib"].url, URL)

    def test_a_url_that_is_not_a_github_release_asset_is_refused(self) -> None:
        for url in [
            f"https://example.com/{WHEEL}",
            f"http://github.com/example-org/gadget-tools/releases/download/v1/{WHEEL}",
            f"https://github.com/example-org/gadget-tools/archive/main/{WHEEL}",
            f"https://github.com.example.com/o/r/releases/download/v1/{WHEEL}",
            f"https://user@github.com/o/r/releases/download/v1/{WHEEL}",
            f"https://github.com/o/r/releases/download/v1/{WHEEL}#sha256={DIGEST}",
            "git+https://github.com/example-org/gadget-tools@main",
        ]:
            with self.subTest(url=url):
                with self.assertRaisesRegex(LockError, "not a GitHub release asset"):
                    self.pins(f"gadget-lib @ {url} --hash=sha256:{DIGEST}\n")

    def test_what_is_not_a_wheel_of_the_named_project_is_refused(self) -> None:
        sdist = URL.replace(WHEEL, "gadget_lib-0.1.0.tar.gz")
        other = URL.replace(WHEEL, "other_lib-0.1.0-py3-none-any.whl")
        with self.assertRaisesRegex(LockError, "not a wheel"):
            self.pins(f"gadget-lib @ {sdist} --hash=sha256:{DIGEST}\n")
        with self.assertRaisesRegex(LockError, "a wheel of other-lib"):
            self.pins(f"gadget-lib @ {other} --hash=sha256:{DIGEST}\n")

    def test_a_url_pin_needs_exactly_one_hash(self) -> None:
        for hashes in ["", f" --hash=sha256:{DIGEST} --hash=sha256:{'e' * 64}"]:
            with self.subTest(hashes=hashes):
                with self.assertRaisesRegex(LockError, "exactly one"):
                    self.pins(f"gadget-lib @ {URL}{hashes}\n")

    def test_the_same_asset_parsed_twice_reads_the_same(self) -> None:
        self.assertEqual(release_asset(URL), release_asset(URL))
        self.assertIsNone(release_asset("https://github.com/o/r"))

    def test_without_url_pins_leaves_every_other_line_as_it_was(self) -> None:
        stripped = without_url_pins(LOCK)

        self.assertNotIn("gadget-lib @", stripped)
        self.assertNotIn(DIGEST, stripped)
        self.assertEqual(stripped, LOCK.replace(
            f"gadget-lib @ {URL} \\\n    --hash=sha256:{DIGEST}\n", ""))
        self.assertEqual(without_url_pins("packaging==26.2\n"), "packaging==26.2\n")


def release(**changes) -> dict:
    document = {
        "draft": False,
        "published_at": "2026-09-01T10:00:00Z",
        "assets": [{"name": WHEEL, "digest": f"sha256:{DIGEST}",
                    "created_at": "2026-09-01T09:59:00Z", "updated_at": "2026-09-01T09:59:30Z"}],
    }
    document.update(changes)
    return document


class DatingAUrlPinTest(LockFixture):
    def pin(self) -> Pin:
        return self.pins()["gadget-lib"]

    @patch("tapio_build_tools.ecosystems.python.cooldown.fetch_json")
    def test_it_is_dated_by_the_later_of_its_upload_and_its_release(self, fetch_json) -> None:
        fetch_json.return_value = release()
        self.assertEqual(python_cooldown._dated(self.pin()).published,
                         published("2026-09-01T10:00:00Z"))

        fetch_json.return_value = release(published_at="2026-08-01T00:00:00Z")
        self.assertEqual(python_cooldown._dated(self.pin()).published,
                         published("2026-09-01T09:59:30Z"))
        self.assertEqual(fetch_json.call_args.args[0], self.pin().asset.api_url)

    @patch("tapio_build_tools.ecosystems.python.cooldown.fetch_json")
    def test_an_asset_that_is_not_the_pinned_file_is_refused(self, fetch_json) -> None:
        document = release()
        document["assets"][0]["digest"] = "sha256:" + "f" * 64
        fetch_json.return_value = document
        with self.assertRaisesRegex(CooldownError, "the release asset is sha256:f"):
            python_cooldown._dated(self.pin())

    @patch("tapio_build_tools.ecosystems.python.cooldown.fetch_json")
    def test_an_asset_github_gives_no_digest_for_is_refused(self, fetch_json) -> None:
        document = release()
        del document["assets"][0]["digest"]
        fetch_json.return_value = document
        with self.assertRaisesRegex(CooldownError, "no digest"):
            python_cooldown._dated(self.pin())

    @patch("tapio_build_tools.ecosystems.python.cooldown.fetch_json")
    def test_a_draft_or_a_release_without_the_asset_is_refused(self, fetch_json) -> None:
        for document, message in [(release(draft=True), "not published"),
                                  (release(published_at=None), "not published"),
                                  (release(assets=[]), f"has no asset {WHEEL}")]:
            with self.subTest(message=message):
                fetch_json.return_value = document
                with self.assertRaisesRegex(CooldownError, message):
                    python_cooldown._dated(self.pin())

    @patch("tapio_build_tools.ecosystems.python.cooldown.fetch_json")
    def test_the_jobs_token_goes_to_the_github_api_and_nowhere_else(self, fetch_json) -> None:
        fetch_json.return_value = release()
        with patch.dict(os.environ, {"GITHUB_TOKEN": "token-value"}):
            python_cooldown._dated(self.pin())
        self.assertEqual(fetch_json.call_args.kwargs["headers"],
                         {"Authorization": "Bearer token-value"})

        fetch_json.return_value = {"urls": [{"digests": {"sha256": "b" * 64},
                                             "upload_time_iso_8601": "2026-01-01T00:00:00Z"}]}
        with patch.dict(os.environ, {"GITHUB_TOKEN": "token-value"}):
            python_cooldown._dated(self.pins()["packaging"])
        self.assertNotIn("headers", fetch_json.call_args.kwargs)

    @patch("tapio_build_tools.ecosystems.python.cooldown.fetch_json")
    def test_a_young_release_is_refused_like_any_other(self, fetch_json) -> None:
        from tapio_build_tools.cooldown import refuse_young
        fetch_json.return_value = release()
        dated = python_cooldown._dated(self.pin())
        with self.assertRaisesRegex(CooldownError, "gadget-lib 0.1.0"):
            refuse_young([dated], dated.published - timedelta(days=1))

    def test_a_lock_error_reads_as_a_cooldown_error(self) -> None:
        self.lock.write_text(f"gadget-lib @ https://example.com/{WHEEL}\n", encoding="utf-8")
        with self.assertRaises(CooldownError):
            python_cooldown.read_pins(self.lock)


class AuditingAUrlPinTest(LockFixture):
    def config(self):
        (self.root / "build-tooling.toml").write_text(
            f"""schema-version = 1
[organization]
name = "Example"
[products.demo]
name = "Demo"
[ecosystems.python]
version = "{sys.version_info.major}.{sys.version_info.minor}"
[[ecosystems.python.requirements]]
name = "runtime"
lock = "requirements.txt"
""",
            encoding="utf-8",
        )
        return load_config(self.root)

    @patch("tapio_build_tools.ecosystems.python.audit.subprocess.run")
    def test_it_is_named_as_not_audited_and_the_rest_is_audited_strictly(self, run) -> None:
        self.lock.write_text(LOCK, encoding="utf-8")
        given = {}
        run.side_effect = lambda command, **_: given.update(
            lock=Path(command[command.index("--requirement") + 1]).read_text(encoding="utf-8"),
            command=command)

        with patch("builtins.print") as printed:
            audit(self.config(), "runtime")

        self.assertIn("--strict", given["command"])
        self.assertEqual(given["lock"], without_url_pins(LOCK))
        self.assertIn("cryptography==50.0.1", given["lock"])
        [[line], _] = printed.call_args
        self.assertTrue(line.startswith(f"not audited: gadget-lib 0.1.0 ({URL})"), line)

    @patch("tapio_build_tools.ecosystems.python.audit.subprocess.run")
    def test_a_lock_without_url_pins_is_audited_as_it_is(self, run) -> None:
        self.lock.write_text("packaging==26.2\n", encoding="utf-8")
        audit(self.config(), "runtime")
        command = run.call_args.args[0]
        self.assertEqual(command[command.index("--requirement") + 1], str(self.lock))

    @patch("tapio_build_tools.ecosystems.python.audit.subprocess.run")
    def test_a_url_that_could_not_be_accounted_for_stops_the_audit(self, run) -> None:
        self.lock.write_text(f"gadget-lib @ https://example.com/{WHEEL}\n", encoding="utf-8")
        with self.assertRaisesRegex(AuditError, "not a GitHub release asset"):
            audit(self.config(), "runtime")
        run.assert_not_called()


class AUrlPinInTheSbomTest(LockFixture):
    def bom(self) -> dict:
        return {
            "bomFormat": "CycloneDX", "specVersion": "1.6",
            "metadata": {"component": {"name": "Demo", "bom-ref": "root"}},
            "dependencies": [{"ref": "root", "dependsOn": ["requirements-L7"]}],
            "components": [
                {"type": "library", "bom-ref": "requirements-L7", "name": "gadget-lib",
                 "purl": f"pkg:pypi/gadget-lib?download_url={URL}",
                 "externalReferences": [{"type": "distribution", "url": URL}]},
                {"type": "library", "bom-ref": "pkg:pypi/packaging@26.2", "name": "packaging",
                 "version": "26.2", "purl": "pkg:pypi/packaging@26.2"},
            ],
        }

    def test_it_gets_the_version_and_hash_it_was_pinned_at(self) -> None:
        bom = self.bom()
        version_url_components(bom, list(self.pins().values()))

        gadget, packaging = bom["components"]
        self.assertEqual(gadget["version"], "0.1.0")
        self.assertEqual(gadget["purl"], f"pkg:pypi/gadget-lib@0.1.0?download_url={URL}")
        self.assertEqual(gadget["hashes"], [{"alg": "SHA-256", "content": DIGEST}])
        self.assertEqual(packaging["purl"], "pkg:pypi/packaging@26.2")

    def test_a_component_left_without_a_version_fails_the_bom(self) -> None:
        from tapio_build_tools.config import Product
        product = Product(id="demo", name="Demo")
        with self.assertRaisesRegex(SbomError, "no version: gadget-lib"):
            _validate_semantics(self.bom(), product, artifact=False)

        bom = self.bom()
        version_url_components(bom, list(self.pins().values()))
        _validate_semantics(bom, product, artifact=False)


