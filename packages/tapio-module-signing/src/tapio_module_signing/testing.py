"""Helpers for a product's tests: keys, a trusted table, and vault-style signing.

Nothing here is used at run time. It is shipped in the package so that every
product signs its test modules the same way the release pipeline does, rather
than each writing its own approximation of it.
"""

from __future__ import annotations

import base64
from collections.abc import Iterator, Mapping
import contextlib
import os
from unittest.mock import patch

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, utils as asym_utils
from cryptography.hazmat.primitives.serialization import (
    Encoding,
    NoEncryption,
    PrivateFormat,
    PublicFormat,
)

from tapio_module_signing import build
from tapio_module_signing.profile import Profile


def generate_key() -> ec.EllipticCurvePrivateKey:
    return ec.generate_private_key(ec.SECP256R1())


def public_b64(key: ec.EllipticCurvePrivateKey) -> str:
    """The public half of *key* as a trusted-key table holds it."""
    return base64.b64encode(key.public_key().public_bytes(
        Encoding.DER, PublicFormat.SubjectPublicKeyInfo)).decode("ascii")


def write_key_file(key: ec.EllipticCurvePrivateKey, path: str) -> str:
    """*key* as the PEM file the builder's --key-file reads."""
    with open(path, "wb") as handle:
        handle.write(key.private_bytes(Encoding.PEM, PrivateFormat.PKCS8, NoEncryption()))
    return path


@contextlib.contextmanager
def trusting(profile: Profile, table: Mapping[str, str]) -> Iterator[None]:
    """Trust exactly *table* for the duration, and the shipped table after.

    Patched rather than assigned, so a failure cannot leave the product
    trusting a key generated by a test.
    """
    with patch.dict(profile.trusted_keys, table, clear=True):  # type: ignore[arg-type]
        yield


def vault_signature(printed_digest: str, key: ec.EllipticCurvePrivateKey) -> str:
    """What `az keyvault key sign` prints for a digest the builder printed.

    az hands the digest to base64.b64decode on the way in, signs the 32 bytes
    as a prehashed SHA-256, and prints r and s concatenated in standard base64.
    """
    digest = base64.b64decode(printed_digest.encode("utf-8"))
    der = key.sign(digest, ec.ECDSA(asym_utils.Prehashed(hashes.SHA256())))
    r, s = asym_utils.decode_dss_signature(der)
    return base64.b64encode(r.to_bytes(32, "big") + s.to_bytes(32, "big")).decode("utf-8")


def build_vault_style(source: str, out: str, key_id: str, key: ec.EllipticCurvePrivateKey,
                      *, profile: Profile, created: str | None = None) -> str:
    """A signed file, built the way the release pipeline builds and signs one.

    The manifest, then its digest decoded the way `az keyvault key sign`
    decodes it, then a signature over that digest - what the vault is handed
    and what it signs - packed with --signature=VALUE as CI passes it. Not the
    --key-file shortcut, which signs the manifest directly and so would skip
    the half of the path the vault is in.
    """
    manifest_path = out + ".manifest.json"
    arguments = ["manifest", "--source", source, "--out", manifest_path]
    if created:
        arguments += ["--created", created]
    with contextlib.redirect_stdout(None):
        build.main(arguments, profile=profile)
    try:
        with open(manifest_path, "rb") as handle:
            printed_digest = build.signing_digest(handle.read(), profile=profile)
        signature = vault_signature(printed_digest, key)
        with contextlib.redirect_stdout(None):
            build.main(["pack", "--source", source, "--manifest", manifest_path,
                        "--key-id", key_id, f"--signature={signature}", "--out", out],
                       profile=profile)
    finally:
        os.remove(manifest_path)
    return out
